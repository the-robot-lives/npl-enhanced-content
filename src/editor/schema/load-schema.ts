/**
 * Editor schema service — loader.
 *
 * Loads `elements.json` at BUNDLE time (a plain import, no fetch — the
 * editor bundle ships the schema it needs; readers of ordinary documents
 * never parse it at runtime). Normalizes the authored shape into
 * `SchemaTagSpec`s (EDITOR.md §3.1) and appends the global attribute
 * catalog (id/kind/tags + audience) to every tag's editable set.
 *
 * `sem-chat` is NOT in elements.json (it is an agent-kit element outside
 * the normative schema — EDITOR.md §3.1). The loader seeds a minimal,
 * schema-complete spec for it so the validator and the attributes-only
 * fallback treat it like any other tag; the data-bucket descriptor lane
 * (Phase 2) ships its hand-written descriptor + jsonItems.
 */

import rawSchema from '../../../elements.json';
import type {
  ElementSchema,
  SchemaAttrSpec,
  SchemaTagSpec,
} from './types.js';

/** Raw elements.json shapes (pre-normalization). Kept loose: the file is
 *  generated by scripts/build-elements-index.mjs and its exact literal type
 *  would slow tsc for no benefit. */
interface RawAttr {
  name: string;
  required?: boolean | null;
  type?: string;
  allowedValues?: string[];
  default?: string | null;
  description?: string;
}

interface RawTag {
  name: string;
  family?: string;
  summary?: string;
  description?: string;
  attributes?: RawAttr[];
  children?: { name: string; note?: string }[];
  example?: string;
  optionsIn?: string;
}

interface RawSchema {
  specVersion?: string;
  tagCount?: number;
  tags?: RawTag[];
}

/** Global attribute catalog appended to every tag (EDITOR.md §3.1).
 *  `audience` is the canonical authoring spelling; `data-audience` is the
 *  element's own mirror write and is regenerated on re-render. */
export const GLOBAL_ATTR_NAMES: readonly string[] = ['id', 'kind', 'tags', 'audience'];

function normalizeAttr(raw: RawAttr, isGlobal: boolean): SchemaAttrSpec {
  return {
    name: raw.name,
    required: raw.required === true,
    type: raw.type ?? '',
    allowedValues: raw.allowedValues ?? [],
    default: raw.default ?? null,
    description: raw.description ?? '',
    global: isGlobal,
  };
}

function normalizeTag(raw: RawTag): SchemaTagSpec {
  const declared = (raw.attributes ?? []).map((a) => normalizeAttr(a, false));
  const missingGlobals = GLOBAL_ATTR_NAMES.filter(
    (g) => !declared.some((a) => a.name.toLowerCase() === g),
  ).map((g) =>
    normalizeAttr(
      { name: g, required: false, description: 'global attribute catalog (conventions.md §2)' },
      true,
    ),
  );
  return {
    name: raw.name,
    family: raw.family === 'npl' ? 'npl' : 'sem',
    summary: raw.summary ?? '',
    description: raw.description ?? raw.summary ?? '',
    attributes: [...declared, ...missingGlobals],
    children: (raw.children ?? []).map((c) => ({ name: c.name, note: c.note ?? '' })),
    example: raw.example ?? '',
    optionsIn: raw.optionsIn ?? null,
  };
}

/**
 * sem-chat — hand-written, schema-complete seed (agent-kit element, not in
 * elements.json). Its payload is a `<script type="application/json">` child;
 * the attribute set is just the global catalog. The data-bucket lane ships
 * the real descriptor (jsonItems) in Phase 2.
 */
export const SEM_CHAT_SPEC: SchemaTagSpec = normalizeTag({
  name: 'sem-chat',
  family: 'sem',
  summary: 'A chat transcript rendered from an inert JSON payload.',
  description:
    'Agent-kit element: one <script type="application/json"> child carries the messages; the element renders them. The editor authors the payload through the JSON items editor — the only script node it writes (EDITOR.md §8).',
  attributes: [],
  children: [{ name: 'script', note: 'type="application/json" payload — parsed as one raw text node' }],
  example: '<sem-chat id="demo">\n  <script type="application/json">[{"role":"user","text":"hi"}]</script>\n</sem-chat>',
});

/**
 * sem-browser — hand-written, schema-complete seed (reader element, not in
 * elements.json). `src` loads a framed document; `label` names it; `resolve`
 * is a host-injection hook name. Authored children are the zero-JS fallback
 * figure. The prose-bucket lane ships the descriptor (Phase 2).
 */
export const SEM_BROWSER_SPEC: SchemaTagSpec = normalizeTag({
  name: 'sem-browser',
  family: 'sem',
  summary: 'A framed document viewport with an inert address bar.',
  description:
    'Reader element: with `src` it frames a fetched document (authored children become the hidden zero-JS fallback); without one it re-homes the authored children into the viewport. The editor edits `src`/`label`/`resolve` and the fallback figure.',
  attributes: [
    { name: 'src' },
    { name: 'label' },
    { name: 'resolve' },
  ],
  children: [{ name: 'figure', note: 'zero-JS fallback shown before upgrade / without JS' }],
  example: '<sem-browser src="/demos/tokens.html" label="Token lifetimes">\n  <figure>Token lifetime chart</figure>\n</sem-browser>',
});

let cached: ElementSchema | null = null;

/** The normalized bundled schema. Memoized — one parse per session. */
export function loadSchema(): ElementSchema {
  if (cached) return cached;
  const raw = rawSchema as unknown as RawSchema;
  const tags = (raw.tags ?? []).map(normalizeTag);
  const byName = new Map<string, SchemaTagSpec>();
  for (const tag of tags) byName.set(tag.name.toLowerCase(), tag);
  // sem-chat rides in the lookup only — element.json tagCount stays honest.
  byName.set('sem-chat', SEM_CHAT_SPEC);
  // Out-of-schema editor tags (sem-chat precedent): lookup-only so their
  // descriptors resolve; element.json tagCount stays honest.
  byName.set('sem-enhanced-document', normalizeTag({ name: 'sem-enhanced-document', family: 'sem', attributes: [] }));
  byName.set('agent', normalizeTag({ name: 'agent', family: 'sem', attributes: [] }));
  byName.set('sem-browser', SEM_BROWSER_SPEC);
  cached = {
    specVersion: raw.specVersion ?? '0',
    tags,
    byName,
  };
  return cached;
}

/** Canonical authoring spelling of a tag reference. Accepts the element
 *  form (`sem-note`), its class alias (`.sem-note` — and `.note`, both
 *  case-insensitive), and the bare sel() name (`note`) tried as sem-note
 *  then npl-note. */
export function canonicalTagName(raw: string): string | null {
  const schema = loadSchema();
  const name = raw.trim().toLowerCase();
  if (name === '') return null;
  // the class token already carries the family prefix (`class="sem-note"`);
  // a bare `.note`/`note` sel() name gets the family prefixes tried
  const stripped = name.startsWith('.') ? name.slice(1) : name;
  if (stripped === '') return null;
  if (schema.byName.has(stripped)) return stripped;
  for (const family of ['sem-', 'npl-']) {
    const candidate = family + stripped;
    if (schema.byName.has(candidate)) return candidate;
  }
  return null;
}

/** Schema spec for a tag reference (same spellings as canonicalTagName). */
export function getTag(raw: string): SchemaTagSpec | undefined {
  const canonical = canonicalTagName(raw);
  return canonical ? loadSchema().byName.get(canonical) : undefined;
}

/** The tag's full editable attribute set: declared schema attrs, then any
 *  global-catalog attrs the tag does not declare itself (marked
 *  `global: true`). Order: declared first, globals appended. */
export function editableAttrsOf(spec: SchemaTagSpec): readonly SchemaAttrSpec[] {
  return spec.attributes; // normalizeTag already appended missing globals
}

/** Tags whose `optionsIn` names `containerTag` — the item/companion tags a
 *  container accepts (sem-facts → sem-fact, sem-properties → sem-property,
 *  …). */
export function companionsOf(containerTag: string): SchemaTagSpec[] {
  const schema = loadSchema();
  const canonical = canonicalTagName(containerTag);
  if (!canonical) return [];
  return schema.tags.filter((t) => t.optionsIn === canonical);
}
